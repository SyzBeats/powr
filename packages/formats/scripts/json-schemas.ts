const OPTIONS = {
  // The input side: what the file contains before Zod's own transforms (`z.json()`).
  io: 'input',
  // Every Zod type used today has a JSON Schema form; a new one that has none must fail here
  // and be handled on purpose, not be published as "anything".
  unrepresentable: 'throw',
  metadata: NAMED,
  override: (ctx) => {
    if (ctx.zodSchema === v1.localDateSchema) ctx.jsonSchema.format = 'date';
  },
} as const satisfies Parameters<typeof z.toJSONSchema>[1];

const GENERATED_BY =
  'Generated by `pnpm formats:schemas` from the Zod schemas the import uses (packages/formats); do not edit. Rules JSON Schema cannot express are listed in docs/formats/backup-format.md.';

function document(title: string, description: string, schema: z.ZodType): string {
  const { $schema, $defs, ...rest } = z.toJSONSchema(schema, OPTIONS) as Record<string, unknown>;
  const defs = $defs as Record<string, unknown> | undefined;
  const ordered = {
    $schema,
    title,
    description: `${description} ${GENERATED_BY}`,
    ...rest,
    ...(defs
      ? { $defs: Object.fromEntries(Object.entries(defs).toSorted(([a], [b]) => (a < b ? -1 : 1))) }
      : {}),
  };
  return `${JSON.stringify(ordered, null, 2)}\n`;
}

/** Every schema file: path relative to {@link SCHEMA_DIR} → its exact text. Deterministic. */
export function jsonSchemaFiles(): Map<string, string> {
  const files = new Map<string, string>();
  files.set(
    `manifest.format-${BACKUP_FORMAT_VERSION}.schema.json`,
    document(
      `POWR backup: manifest.json (formatVersion ${BACKUP_FORMAT_VERSION})`,
      'The first entry of every POWR backup ZIP: versions, creation time, record counts and the SHA-256 checksums of the data entries.',
      manifestSchema,
    ),
  );
  for (const [version, tables] of Object.entries(DATA_VERSION_SCHEMAS)) {
    for (const [table, schema] of Object.entries(tables) as [RawTableName, z.ZodType][]) {
      files.set(
        `data-${version}/${table}.schema.json`,
        document(
          `POWR backup: data/${table}.json (dataVersion ${version})`,
          `A JSON array of ${table} records, sorted by ${RAW_TABLE_KEYS[table]}.`,
          z.array(schema),
        ),
      );
    }
  }
  return files;
}

interface NodeProcess {
  getBuiltinModule(id: 'node:fs'): FileSystem;
  readonly stdout: { write(text: string): void };
}

interface FileSystem {
  rmSync(path: URL, options: { recursive: true; force: true }): void;
  mkdirSync(path: URL, options: { recursive: true }): void;
  writeFileSync(path: URL, text: string): void;
}

/** Replaces the schema directory with freshly generated files. */
function writeJsonSchemas(): void {
  const { process } = globalThis as unknown as { process: NodeProcess };
  const fs = process.getBuiltinModule('node:fs');
  const dir = new URL(`../../../${SCHEMA_DIR}/`, import.meta.url);
  const files = jsonSchemaFiles();
  fs.rmSync(dir, { recursive: true, force: true });
  for (const [path, text] of files) {
    const file = new URL(path, dir);
    fs.mkdirSync(new URL('./', file), { recursive: true });
    fs.writeFileSync(file, text);
  }
  process.stdout.write(`Wrote ${files.size} JSON Schemas to ${SCHEMA_DIR}/.\n`);
}

if ((import.meta as ImportMeta & { main?: boolean }).main) writeJsonSchemas();
